DROP DATABASE IF EXISTS db_fake_news;
CREATE DATABASE db_fake_news;
USE db_fake_news;

-- 1. Tabla de Dimensión: Autor (Ampliado a 100 caracteres por seguridad)
CREATE TABLE DIM_AUTOR (
    ID_AUTOR SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT, 
    AUTOR VARCHAR(100) NULL,
    PRIMARY KEY (ID_AUTOR),
    UNIQUE (AUTOR)
);

-- 2. Tabla de Dimensión: Fuente
CREATE TABLE DIM_FUENTE (
    ID_FUENTE SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT, 
    FUENTE VARCHAR(100) NULL,
    PRIMARY KEY (ID_FUENTE),
    UNIQUE (FUENTE)
);

-- 3. Tabla de Dimensión: País (Estandarizado a ID_PAIS para sincronizar con Python)
CREATE TABLE DIM_PAIS (
    ID_PAIS SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT, 
    PAIS VARCHAR(100) NULL,
    PRIMARY KEY (ID_PAIS),
    UNIQUE (PAIS)
);

-- 4. Tabla de Dimensión: Tipo (Cambiado VARCHAR por ENUM para flexibilidad total con Pandas)
CREATE TABLE DIM_TIPO (
    ID_TIPO SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT, 
    TIPO VARCHAR(100) NULL,
    PRIMARY KEY (ID_TIPO),
    UNIQUE (TIPO)
);

-- 5. Tabla de Hechos: TB_HECHOS (Unificados tipos numéricos unsigned con las dimensiones)
CREATE TABLE TB_HECHOS (
    T_ID SMALLINT UNSIGNED NOT NULL,
    TITULO VARCHAR(300) NULL,
    ID_TIPO SMALLINT UNSIGNED NULL,
    ID_AUTOR SMALLINT UNSIGNED NULL, 
    ID_FUENTE SMALLINT UNSIGNED NULL, 
    ID_PAIS SMALLINT UNSIGNED NULL,
    FAKE TINYINT UNSIGNED NULL,
    TIEMPO SMALLINT UNSIGNED NULL,
    COMPARTIR_TIEMPO SMALLINT UNSIGNED NULL,
    TEXTO MEDIUMTEXT NULL,
    PRIMARY KEY (T_ID),
    FOREIGN KEY (ID_TIPO) REFERENCES DIM_TIPO(ID_TIPO),
    FOREIGN KEY (ID_AUTOR) REFERENCES DIM_AUTOR(ID_AUTOR), 
    FOREIGN KEY (ID_FUENTE) REFERENCES DIM_FUENTE(ID_FUENTE),
    FOREIGN KEY (ID_PAIS) REFERENCES DIM_PAIS(ID_PAIS)
);

-- 6. Tabla Complementaria: TB_METADATOS (Estructura de métricas con espacio de almacenamiento seguro)
CREATE TABLE TB_METADATOS (
    T_ID SMALLINT UNSIGNED NOT NULL,
    VISITAS DECIMAL(9, 1) NULL,
    COMPARTIR DECIMAL(9, 1) NULL,
    DURACION SMALLINT NULL,
    FAVORITO DECIMAL(9, 1) NULL,
    PRIMARY KEY (T_ID),
    FOREIGN KEY (T_ID) REFERENCES TB_HECHOS(T_ID)
);

-- 7. Consulta de Verificación Estructural Inicial
SELECT 'TABLAS CREADAS CON ÉXITO' AS Estado, COUNT(*) AS Total_Tablas 
FROM information_schema.tables 
WHERE table_schema = 'db_fake_news';